      }]}' | has -E '"status" *: *"(OK|CREATED)"'
  else
    ix DELETE "/_plugins/_security/api/roles/$GRAFANA_ROLE" >/dev/null 2>&1; return 0
  fi
}
grafana_indexer_user() {       # add|remove the read-only indexer user "grafana" (kept in internal_users.yml,
  local mode="$1" h=""         # so later securityadmin pushes - e.g. vexor passwd - keep it)
  is_running wazuh1.indexer || { warn "wazuh1.indexer not running - grafana indexer user not changed"; return 1; }
  if [ "$mode" = add ]; then
    ix DELETE "/_plugins/_security/api/roles/wazuhctl_grafana" >/dev/null 2>&1   # pre-rename role name
    grafana_role add || { bad "could not create the indexer role $GRAFANA_ROLE"; return 1; }
    h="$(hash_pw "$(env_get GRAFANA_INDEXER_PASSWORD)")"; [ -n "$h" ] || { bad "hashing failed"; return 1; }
  fi
  cp "$INTERNAL_USERS" "$RUN_TMP/internal_users.bak"
  python3 -I - "$INTERNAL_USERS" "$mode" "$h" <<'PY'
import re, sys
path, mode, h = sys.argv[1:4]
s = open(path).read()
s = re.sub(r"(?m)^grafana:\n(?:[ \t]+.*\n|[ \t]*\n)*", "", s)
if mode == "add":
    s = s.rstrip("\n") + '\n\ngrafana:\n  hash: "' + h + '"\n  reserved: false\n  opendistro_security_roles:\n    - "vexor_grafana"\n  description: "vexor: read-only indexer user for Grafana"\n'
open(path, "w").write(s)
PY
  if securityadmin_users > "$RUN_TMP/secadmin.log" 2>&1; then
    if [ "$mode" = add ]; then ok "indexer user 'grafana' ready (role $GRAFANA_ROLE: read-only, Wazuh indices only)"
    else grafana_role remove; ok "indexer user 'grafana' and role $GRAFANA_ROLE removed"; fi
  else
    cp "$RUN_TMP/internal_users.bak" "$INTERNAL_USERS"; tail -n 8 "$RUN_TMP/secadmin.log"; bad "securityadmin failed - internal_users.yml restored"; return 1
  fi
}
grafana_user_exists() { grep -q '^grafana:' "$INTERNAL_USERS" 2>/dev/null; }
suricata_update_rules() {      # suricata-update runs as root in the container; Suricata itself runs as user
  # "suricata" and must be able to read the result - fix ownership, then hot-reload the rules (USR2)
  dc exec -T suricata sh -c "suricata-update ${1:-} >/dev/null 2>&1; rc=\$?; chown -R suricata:suricata /var/lib/suricata 2>/dev/null; exit \$rc" || return 1
  dc kill -s USR2 suricata >/dev/null 2>&1
}
suricata_sig_count() {         # signatures in the running engine (from the last load/reload in suricata.log)
  local n; n="$(grep -oE "[0-9]+ signatures processed" "$TOOLS_DATA/suricata/log/suricata.log" 2>/dev/null | tail -1 | cut -d" " -f1)"
  echo "${n:-0}"
}
suricata_rules_ensure() {      # the image ships without rules: download ET Open once, then reload
  is_running suricata || return 0
  if dc exec -T --user suricata suricata test -r /var/lib/suricata/rules/suricata.rules 2>/dev/null      && [ "$(suricata_sig_count)" -gt 0 ]; then return 0; fi
  say "downloading Suricata rules (ET Open) ..."
  if suricata_update_rules -f; then
    sleep 20; ok "suricata rules installed and loaded ($(suricata_sig_count) signatures)"
  else
    warn "suricata-update failed (internet access?) - retry: vexor tools update-rules"
  fi
}
tools_prepare() {              # before `docker compose up`: secrets, files, master localfiles, profiles, override, nginx
  ensure_tools_compose
  tools_validate_ports || die "fix the tool ports in .env, then retry"
  if tool_on grafana; then gen_secret GRAFANA_ADMIN_PASSWORD; gen_secret GRAFANA_INDEXER_PASSWORD; grafana_provision; fi
  if tool_on portainer; then
    gen_secret PORTAINER_ADMIN_PASSWORD
    mkdir -p "$TOOLS_DIR/portainer"; printf '%s' "$(env_get PORTAINER_ADMIN_PASSWORD)" > "$TOOLS_DIR/portainer/admin_password"
    chmod 600 "$TOOLS_DIR/portainer/admin_password"
  fi
  tool_on n8n && gen_secret N8N_ENCRYPTION_KEY hex
  if tool_on suricata || tool_on zeek; then
    [ -n "$(env_get SNIFF_INTERFACE)" ] || { env_set SNIFF_INTERFACE "$(sniff_iface)"; say "SNIFF_INTERFACE=$(sniff_iface) (default route) - change it in .env if needed"; }
    ip -o link show "$(sniff_iface)" >/dev/null 2>&1 || die "SNIFF_INTERFACE=$(sniff_iface) does not exist (see: ip -br link)"
  fi
  tool_on suricata && mkdir -p "$TOOLS_DATA/suricata/log"
  if tool_on zeek; then
    mkdir -p "$TOOLS_DATA/zeek/logs" "$TOOLS_DIR/zeek"
    cat > "$TOOLS_DIR/zeek/vexor.zeek" <<'EOF'
# GENERATED by vexor - Zeek in a container without zeekctl: JSON logs, hourly rotation in the log dir.
@load local
redef LogAscii::use_json = T;
redef Log::default_rotation_interval = 1 hr;
EOF
  fi
  write_tool_rules
  TOOLS_MASTER_CHANGED=0 N8N_BLOCKS_CHANGED=0
  soc_wazuh && [ "$(sync_master_localfiles)" = changed ] && TOOLS_MASTER_CHANGED=1
  VULN_CHANGED=0; soc_wazuh && [ "$(sync_vuln_detection)" = changed ] && VULN_CHANGED=1
  SCA_CHANGED=0; soc_wazuh && [ "$(sync_sca)" = changed ] && SCA_CHANGED=1
  [ "$(n8n_sync_blocks)" = changed ] && N8N_BLOCKS_CHANGED=1
  sync_profiles; render_override; render_nginx
}
tools_post() {                 # after `docker compose up`: manager reload, users, rules, nginx
  local again=""
  N8N_INSTALLED=""
  soc_wazuh && [ -n "$(n8n_hook)" ] && n8n_install_script
  if [ "${N8N_BLOCKS_CHANGED:-0}" = 1 ]; then again="$(enabled_managers)"
  else again="$N8N_INSTALLED"; [ "${TOOLS_MASTER_CHANGED:-0}" = 1 ] && again="$again wazuh.master"; fi
  [ "${SCA_CHANGED:-0}" = 1 ] && again="$(enabled_managers)"      # the SCA switch lives in every manager's ossec.conf
  [ "${VULN_CHANGED:-0}" = 1 ] && again="$(enabled_managers)"     # the vulnerability feed switch lives in every manager's ossec.conf
  again="$(tr ' ' '\n' <<<"$again" | grep -v '^$' | sort -u | while read -r m; do is_running "$m" && echo "$m"; done | tr '\n' ' ')"
  if [ -n "${again// /}" ]; then
    say "recreating $again- they load the sensor log sources / n8n integration (agents reconnect by themselves)"
    dc_restart $again >/dev/null 2>&1
  fi
  [ "${VULN_CHANGED:-0}" = 1 ] && ! vuln_on && vuln_feed_clear
  if tool_on grafana; then
    { grafana_user_exists && grafana_user_ok && ! grep -q wazuhctl_grafana "$INTERNAL_USERS"; } || grafana_indexer_user add
  elif grafana_user_exists; then
    grafana_indexer_user remove
  fi
  tool_on suricata && suricata_rules_ensure
  nginx_reload >/dev/null 2>&1 || true
  return 0
}
tools_status() {
  hdr "Tools (set <NAME>=true|false in .env, then: vexor tools apply)"
  printf '  %-10s %-8s %-10s %s\n' TOOL ENABLED STATE "ACCESS / NOTE"
  local t on st note
  for t in "${TOOLS[@]}"; do
    on=no; tool_on "$t" && on=yes
    st="$(dc_all ps --format '{{.State}}' "$t" 2>/dev/null | head -1)"; st="${st:--}"
    case "$t" in
      n8n|grafana|portainer) note="https://$(public_host):$(tool_port "$t")" ;;
      *) note="sniffs $(sniff_iface) -> Wazuh (master)" ;;
    esac
    printf '  %-10s %-8s %-10s %s  - %s\n' "$t" "$on" "$st" "$note" "$(tool_desc "$t")"
  done
  tool_on grafana && say "grafana login: admin / GRAFANA_ADMIN_PASSWORD (vexor config get GRAFANA_ADMIN_PASSWORD) - dashboard: Wazuh / Wazuh alerts overview"
  tool_on portainer && say "portainer login: admin / PORTAINER_ADMIN_PASSWORD (only applied on its first start)"
  tool_on n8n && say "n8n: the FIRST person who opens it creates the owner account - open it right after enabling; then: vexor n8n connect && vexor n8n workflow"
  return 0
}
tools_maintenance() {          # daily: rotate sensor logs, prune old ones, refresh Suricata rules
  local keep; keep="$(env_def TOOLS_LOG_RETENTION_DAYS 7)"
  if tool_on suricata && is_running suricata; then
    local d="$TOOLS_DATA/suricata/log" f
    for f in eve.json fast.log stats.log suricata.log; do
      [ -s "$d/$f" ] && mv "$d/$f" "$d/$f.$(date +%Y%m%d)"
    done
    dc kill -s HUP suricata >/dev/null 2>&1          # suricata reopens its log files
    find "$d" -type f -name '*.[0-9]*' -mtime "+$keep" -delete 2>/dev/null
    suricata_update_rules && log "suricata rules updated"
  fi
  if tool_on zeek; then
    find "$TOOLS_DATA/zeek/logs" -type f -name '*.*-*.log' -mtime "+$keep" -delete 2>/dev/null
  fi
  return 0
}
cmd_tools() {
  local sub="${1:-status}"; shift || true
  case "$sub" in
    status|ls) tools_status ;;
    apply)
      take_lock; preflight
      apply_all; tools_status ;;
    enable|disable|on|off)
      local t="${1:-}" v=true; [[ "$sub" == disable || "$sub" == off ]] && v=false
      tool_var "$t" >/dev/null 2>&1 || die "usage: vexor tools $sub <${TOOLS[*]}>"
      env_set "$(tool_var "$t")" "$v"; ok "$(tool_var "$t")=$v"
      cmd_tools apply ;;
    update-rules)
      tool_on suricata || die "SURICATA is not enabled"
      take_lock
      suricata_update_rules -f && sleep 20 && ok "suricata rules updated and reloaded ($(suricata_sig_count) signatures)" ;;
    *) die "usage: vexor tools [status] | apply | enable <tool> | disable <tool> | update-rules   (tools: ${TOOLS[*]})" ;;
  esac
}

