tool_server_block() {          # nginx https server for one web tool (resolved at request time, so nginx
  local t="$1"                 # still starts while the tool container is being created)
  sed -e "s|@NAME@|$t|g" -e "s|@PORT@|$(tool_port "$t")|g" -e "s|@UP@|$(tool_upstream "$t")|g" <<'EOF'
    # ---- tool: @NAME@  ->  https://<host>:@PORT@   (managed by vexor from .env)
    server {
        listen @PORT@ ssl;
        server_name _;
        error_page 497 =301 https://$http_host$request_uri;
        ssl_certificate     /etc/nginx/certs/proxy.pem;
        ssl_certificate_key /etc/nginx/certs/proxy-key.pem;
        ssl_protocols       TLSv1.2 TLSv1.3;
        client_max_body_size 100m;
        resolver 127.0.0.11 valid=30s ipv6=off;
        location / {
            set $tool_upstream @UP@;
            proxy_pass $tool_upstream;
            proxy_ssl_verify off;
            proxy_http_version 1.1;
            proxy_set_header Host              $host:$server_port;
            proxy_set_header X-Real-IP         $remote_addr;
            proxy_set_header X-Forwarded-For   $proxy_add_x_forwarded_for;
            proxy_set_header X-Forwarded-Proto $scheme;
            proxy_set_header Upgrade           $http_upgrade;
            proxy_set_header Connection        $connection_upgrade;
            proxy_read_timeout 300s;
        }
    }
EOF
}
