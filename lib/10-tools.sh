sync_master_localfiles() {     # sensor logs -> master ossec.conf (localfile); prints "changed" when it edited the file
  local zl; zl="$(env_def ZEEK_WAZUH_LOGS notice,weird,dns,http,ssl,ssh)"
  python3 -I - "$CLUSTER_DIR/wazuh_manager.conf" "$(tool_on suricata && echo 1 || echo 0)" "$(tool_on zeek && echo 1 || echo 0)" "$zl" <<'PY'
import re, sys
path, sur, zeek, zlogs = sys.argv[1], sys.argv[2] == "1", sys.argv[3] == "1", [x.strip() for x in sys.argv[4].split(",") if x.strip()]
s = open(path).read(); o = s
pat = re.compile(r"[ \t]*<!-- (?:vexor|wazuhctl):sensors:begin.*?<!-- (?:vexor|wazuhctl):sensors:end -->\n?", re.S)
lf = []
if sur:   # alerts + anomalies only: stats/flow records have hundreds of fields ("Too many fields for JSON decoder")
    lf.append(("json", "/var/log/suricata/eve.json", '"event_type":"(alert|anomaly)"'))
if zeek:
    lf += [("json", f"/var/log/zeek/{n}.log", "") for n in zlogs]
if lf:
    blk = "  <!-- vexor:sensors:begin (managed by: vexor tools - SURICATA/ZEEK in .env) -->\n"
    for fmt, loc, only in lf:
        rst = f'    <restrict type="PCRE2">{only}</restrict>\n' if only else ""
        blk += f"  <localfile>\n    <log_format>{fmt}</log_format>\n    <location>{loc}</location>\n{rst}  </localfile>\n"
    blk += "  <!-- vexor:sensors:end -->\n"
else:
    blk = ""
# replace the block where it is (keeps its position next to other managed blocks); append only when missing
if pat.search(s):
    first = [True]
    s = pat.sub(lambda m: (blk if first.pop() else "") if first else "", s)
elif blk:
    s = s.replace("</ossec_config>", blk + "</ossec_config>", 1)
if s != o:
    open(path, "w").write(s)          # in-place write keeps the bind-mounted inode
    print("changed")
PY
}
vuln_on() { [[ "$(env_def WAZUH_VULN_DETECTION false)" =~ ^(true|yes|on|1)$ ]]; }
vuln_feed_bytes() {            # vuln_feed_bytes <manager>: bytes of the downloaded CVE feed in its queue volume
  dc exec -T "$1" sh -c 'du -sb /var/ossec/queue/vd /var/ossec/queue/vd_updater 2>/dev/null | awk "{s+=\$1} END {print s+0}"' 2>/dev/null | tr -dc 0-9
}
vuln_feed_clear() {            # detection off: delete the feed it downloaded (13 GB or so per manager); turning it on downloads it again
  local m b total=0
  for m in $(enabled_managers); do
    is_running "$m" || continue
    b="$(vuln_feed_bytes "$m")"; [ "${b:-0}" -gt 0 ] || continue
    dc exec -T "$m" rm -rf /var/ossec/queue/vd /var/ossec/queue/vd_updater >/dev/null 2>&1 && total=$((total + b))
  done
  [ "$total" -gt 0 ] && ok "vulnerability feed removed from the managers ($((total / 1048576)) MB freed)"
  return 0
}
