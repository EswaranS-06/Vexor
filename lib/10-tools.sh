# shellcheck shell=bash
# vexor lib/10-tools.sh - optional tools (n8n, grafana, portainer, suricata, zeek): compose + config
# Sourced by ./vexor in a fixed order (see the loader there); not executable on its own.
# ============================================================== optional tools (N8N, GRAFANA, PORTAINER, SURICATA, ZEEK)
# Each tool is a compose profile in docker-compose.tools.yml, switched on by <NAME>=true in .env.
# Web tools (n8n, grafana, portainer) are published ONLY through nginx on their own 5XXXX port with the
# dashboard certificate. Sensors (suricata, zeek) sniff SNIFF_INTERFACE on the host network; their logs
# are mounted read-only into the master, which reads them (localfile) and alerts with Wazuh rules.
tool_var() { case "$1" in kibana) echo KIBANA ;; n8n) echo N8N ;; grafana) echo GRAFANA ;; portainer) echo PORTAINER ;; suricata) echo SURICATA ;; zeek) echo ZEEK ;; *) return 1 ;; esac; }
tool_on() { local v; v="$(env_def "$(tool_var "$1")" false)"; [[ "${v,,}" =~ ^(true|yes|on|1)$ ]]; }
enabled_tools() { local t; for t in "${TOOLS[@]}"; do tool_on "$t" && echo "$t"; done; return 0; }
web_tools() { local t; for t in "${WEB_TOOLS[@]}"; do tool_on "$t" && echo "$t"; done; soc_elk && echo kibana; return 0; }
tool_port() {
  case "$1" in
    kibana) env_def KIBANA_PORT 55601 ;; n8n) env_def N8N_PORT 55678 ;; grafana) env_def GRAFANA_PORT 53000 ;; portainer) env_def PORTAINER_PORT 59443 ;;
  esac
}
tool_upstream() { case "$1" in kibana) echo "http://kibana:5601" ;; n8n) echo "http://n8n:5678" ;; grafana) echo "http://grafana:3000" ;; portainer) echo "https://portainer:9443" ;; esac; }
tool_desc() {
  case "$1" in
    kibana) echo "ELK - search and dashboards (login elastic)" ;; n8n) echo "workflow automation" ;; grafana) echo "dashboards on the Wazuh alerts" ;; portainer) echo "container management / monitoring" ;;
    suricata) echo "network IDS -> Wazuh alerts" ;; zeek) echo "network logs (conn, dns, http, ssl...) -> Wazuh" ;;
  esac
}
sniff_iface() {
  local i; i="$(env_get SNIFF_INTERFACE)"
  [ -n "$i" ] || i="$(ip -4 route show default 2>/dev/null | awk '{for(k=1;k<=NF;k++) if($k=="dev"){print $(k+1); exit}}')"
  echo "${i:-eth0}"
}
file_fresh() { [ -f "$1" ] && [ -n "$(find "$1" -mmin -"$2" 2>/dev/null)" ]; }
gen_secret() {                 # gen_secret KEY [hex]: generate a value when it is empty or CHANGE_ME
  local v; v="$(env_get "$1")"
  [ -n "$v" ] && [ "$v" != CHANGE_ME ] && return 0
  if [ "${2:-}" = hex ]; then env_set "$1" "$(openssl rand -hex 24)"; else env_set "$1" "$(gen_pw)"; fi
  chmod 600 "$ENV_FILE"; say "generated $1"
}
tools_validate_ports() {       # web tool ports: 50000-59999, unique, not used by other services/programs
  local t p seen=" $(env_def PROXY_PORT 8080) $(env_def AGENT_PORT 1514) $(env_def ENROLL_PORT 1515) $(env_def API_PORT 55000) $(indexer_port) " ok=0
  console_on && seen+="$(console_port) "
  soc_elk && seen+="$(es_port) $(env_def LOGSTASH_BEATS_PORT 55044) "
  for t in $(web_tools); do
    p="$(tool_port "$t")"
    if ! [[ "$p" =~ ^5[0-9]{4}$ ]]; then bad "$(tool_var "$t")_PORT=$p - tool ports must be in 50000-59999"; ok=1; continue; fi
    if [[ "$seen" == *" $p "* ]]; then bad "$(tool_var "$t")_PORT=$p is already used by another service in .env"; ok=1; continue; fi
    seen+="$p "
    if port_listening "$p" && ! docker ps --format '{{.Names}} {{.Ports}}' | grep -E "nginx" | has ":$p->"; then
      bad "port $p ($(tool_var "$t")_PORT) is used by another program: $(ss -Hltnp "( sport = :$p )" | awk '{print $NF}' | head -1)"; ok=1
    fi
  done
  return "$ok"
}
