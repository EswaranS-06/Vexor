cmd_soc() {
  local target="${1:-status}"; shift || true
  case "$target" in
    status)
      hdr "SOC=$(soc)"
      soc_wazuh && say "Wazuh   : $(layout_desc)"
      soc_elk && say "ELK     : Elastic $(elk_version) - Kibana https://$(public_host):$(env_def KIBANA_PORT 55601), Beats -> $(public_host):$(env_def LOGSTASH_BEATS_PORT 55044)"
      [ "$(soc)" = both ] && say "Wazuh alerts are copied into Elasticsearch (vexor-wazuh-alerts-*)"
      hint "switch: vexor soc wazuh | elk | both   (data of a stack that is switched off stays in its volumes)" ;;
    wazuh|elk|both)
      local cur; cur="$(soc)"
      [ "$cur" = "$target" ] && { ok "already SOC=$target"; return 0; }
      [ "$target" = elk ] && warn "SOC=elk stops Wazuh: agents cannot report until you switch back (their keys and all alerts are kept)"
      [ "$cur" != wazuh ] && [ "$target" = wazuh ] && say "ELK is stopped; its data stays in the elk-* volumes"
      confirm "Switch SOC $cur -> $target?" || die "Aborted"
      take_lock; preflight
      env_set SOC "$target"; echo "$(ts) soc $target (from $cur)" >> "$HISTORY_FILE"
      apply_all
      ok "SOC=$target" ;;
    *) die "usage: vexor soc [status] | wazuh | elk | both" ;;
  esac
}
enroll_password_sync() {       # use_password=yes without authd.pass: authd picks a random password nobody knows and no agent can enroll
  local conf="$CLUSTER_DIR/wazuh_manager.conf" pw
  grep -q '<use_password>yes</use_password>' "$conf" 2>/dev/null || return 0
  is_running wazuh.master || return 0
  pw="$(env_get AGENT_ENROLL_PASSWORD)"
  if [ -z "$pw" ]; then pw="$(openssl rand -hex 16)"; env_set AGENT_ENROLL_PASSWORD "$pw"; fi
  [ "$(dc exec -T wazuh.master cat /var/ossec/etc/authd.pass 2>/dev/null | tr -d '\r\n')" = "$pw" ] && return 0
  dc exec -T wazuh.master bash -c "printf '%s\n' '$pw' > /var/ossec/etc/authd.pass && chown root:wazuh /var/ossec/etc/authd.pass && chmod 640 /var/ossec/etc/authd.pass" \
    && dc_restart wazuh.master >/dev/null && ok "enrollment password restored (authd.pass was missing or different)"
  return 0
}
apply_all() {                  # the one reconcile path: render everything, pull, up, post-steps
  tools_prepare; elk_prepare
  pull_missing_images || warn "some images are missing - their services will not start"
  prune_disabled_containers
  dashboard_yml_sync
  run_step "Starting the containers" dc up -d || die "docker compose up failed - see the output above, then: vexor doctor"
  soc_wazuh && wait_indexer 300 && post_start      # users/roles below need a running indexer
  tools_post
  soc_wazuh && enroll_password_sync   # authd.pass must exist whenever use_password is yes
  soc_wazuh && detection_sync      # custom rules/decoders/lists back into a master with a fresh volume
  elk_post
  soc_wazuh && wait_dashboard 240
  nginx_reload >/dev/null 2>&1 || true
  console_sync || true
  record_applied_env
  return 0
}
cmd_elk() {
  case "${1:-status}" in
    status) soc_elk || die "ELK is off (SOC=$(soc)) - enable it: vexor soc both|elk"; hdr "ELK (Elastic $(elk_version))"; elk_status_lines
            say "Beats / Elastic Agent -> $(public_host):$(env_def LOGSTASH_BEATS_PORT 55044)   (vexor elk beats-config)" ;;
    explain) es_curl GET /_cluster/allocation/explain?pretty ;;
    reset-password)
      soc_elk || die "ELK is off"
      take_lock
      local np; np="$(gen_pw)"
      say "resetting the elastic password inside the container ..."
      if dc exec -T elasticsearch bin/elasticsearch-reset-password -u elastic -b -s --url http://localhost:9200 >"$RUN_TMP/espw" 2>/dev/null; then
        local gen; gen="$(tr -d '\r\n' < "$RUN_TMP/espw")"
        env_set ELASTIC_PASSWORD "$gen"; chmod 600 "$ENV_FILE"
        es_curl POST /_security/user/elastic/_password -d "{\"password\":\"$np\"}" >/dev/null && env_set ELASTIC_PASSWORD "$np"
        ok "elastic password reset and stored in .env"; elk_post
      else bad "reset failed - vexor logs elasticsearch"; fi ;;
    indices) es_curl GET '/_cat/indices/vexor-*?v&s=index&h=health,index,docs.count,store.size&expand_wildcards=open' ;;
    search) shift; soc_elk || die "ELK is off"; elk_search "$@" ;;
    data-views) soc_elk || die "ELK is off"; elk_data_views ;;
    retention) soc_elk || die "ELK is off"; elk_retention_apply ;;
    beats-config|filebeat) soc_elk || die "ELK is off"; elk_beats_config ;;
    beats-ca) logstash_tls_on || die "LOGSTASH_BEATS_TLS is off"; cat "$LS_CERT_DIR/ca.crt" 2>/dev/null || die "no certificate yet - vexor config apply" ;;
    es) shift; soc_elk || die "ELK is off"; local m="${1:?usage: vexor elk es <METHOD> <path> [json]}" pth="${2:?path}"; shift 2
        if [ $# -gt 0 ]; then es_curl "$m" "$pth" -d "$1"; else es_curl "$m" "$pth"; fi; echo ;;
    logs) shift; cmd_logs "${@:-elasticsearch}" ;;
    *) die "usage: vexor elk [status] | indices | search [query] [-n N] [--index P] | data-views | retention
                | beats-config | beats-ca | es <METHOD> <path> [json] | explain | reset-password | logs [svc]" ;;
  esac
}

