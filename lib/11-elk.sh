# shellcheck shell=bash
# vexor lib/11-elk.sh - SOC wazuh|elk|both, ELK, Logstash Beats input over TLS
# Sourced by ./vexor in a fixed order (see the loader there); not executable on its own.
# ============================================================== SOC: wazuh | elk | both
# SOC=wazuh : Wazuh (managers, indexers, dashboard) - the default
# SOC=elk   : Elasticsearch + Logstash + Kibana only (sensors and Beats feed Logstash)
# SOC=both  : Wazuh + ELK; Logstash also ships every Wazuh alert into Elasticsearch
# nginx is in front in every mode (Kibana on KIBANA_PORT, web tools on their ports).
soc() { local s; s="$(env_def SOC wazuh)"; s="${s,,}"; [[ "$s" =~ ^(wazuh|elk|both)$ ]] || s=wazuh; echo "$s"; }
soc_wazuh() { [ "$(soc)" != elk ]; }
soc_elk() { [ "$(soc)" != wazuh ]; }
elk_version() { env_def ELK_VERSION 9.5.4; }
es_port() { env_def ES_PORT 59200; }
es_curl() {                    # es_curl <METHOD> <path> [curl args]  - as the elastic superuser, via 127.0.0.1:ES_PORT
  local m="$1" p="$2"; shift 2
  curl -sS --connect-timeout 5 -u "elastic:$(env_get ELASTIC_PASSWORD)" -X "$m" -H 'Content-Type: application/json' \
       "http://127.0.0.1:$(es_port)$p" "$@"
}
es_code() { curl -s -o /dev/null -w '%{http_code}' --max-time 10 -u "elastic:$(env_get ELASTIC_PASSWORD)" "http://127.0.0.1:$(es_port)${1:-/}" 2>/dev/null || true; }
kibana_code() { curl -sk -o /dev/null -w '%{http_code}' --max-time 10 "https://$(local_ip):$(env_def KIBANA_PORT 55601)${1:-/api/status}" 2>/dev/null || true; }
