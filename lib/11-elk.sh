# ============================================================== Logstash Beats input over TLS
# LOGSTASH_BEATS_TLS=true: the Beats input on LOGSTASH_BEATS_PORT only accepts TLS. Server certificate signed by the
# stack's internal root CA (config/wazuh_indexer_ssl_certs/root-ca.pem); senders trust that CA (vexor elk beats-ca).
LS_CERT_DIR="$ROOT/config/elk/logstash/certs"
logstash_tls_on() { [[ "$(env_def LOGSTASH_BEATS_TLS false)" =~ ^(true|yes|on|1)$ ]]; }
logstash_sans() {
  local s="DNS:logstash,DNS:localhost,IP:127.0.0.1" h ip; h="$(public_host)"
  if [[ "$h" =~ ^[0-9]+(\.[0-9]+){3}$ ]]; then s+=",IP:$h"; else s+=",DNS:$h"; fi
  for ip in $(host_ips); do [[ ",$s," == *",IP:$ip,"* ]] || s+=",IP:$ip"; done
  echo "$s"
}
logstash_certs() {             # issue/renew the Beats server certificate (only when TLS is on)
  mkdir -p "$LS_CERT_DIR"
  logstash_tls_on || return 0
  local d="$LS_CERT_DIR" ca="$INT_CERT_DIR/root-ca.pem" cakey="$INT_CERT_DIR/root-ca.key" sans
  [ -f "$ca" ] && [ -f "$cakey" ] || { warn "internal CA missing - Beats TLS needs: vexor install"; return 1; }
  sans="$(logstash_sans)"
  if [ -s "$d/logstash.crt" ] && [ -s "$d/logstash.key" ] && [ "$(cat "$d/sans" 2>/dev/null)" = "$sans" ] \
     && [ "$(cert_days_left "$d/logstash.crt")" -gt 30 ] && cmp -s "$ca" "$d/ca.crt"; then
    return 0
  fi
  openssl req -new -newkey rsa:2048 -nodes -keyout "$RUN_TMP/ls.key" -subj "/CN=logstash/O=Vexor" -out "$RUN_TMP/ls.csr" 2>/dev/null \
    && printf 'subjectAltName=%s\nextendedKeyUsage=serverAuth\nkeyUsage=digitalSignature,keyEncipherment\n' "$sans" > "$RUN_TMP/ls.ext" \
    && openssl x509 -req -in "$RUN_TMP/ls.csr" -CA "$ca" -CAkey "$cakey" -CAcreateserial -CAserial "$RUN_TMP/ls.srl" \
         -days 825 -sha256 -extfile "$RUN_TMP/ls.ext" -out "$d/logstash.crt" 2>/dev/null \
    && openssl pkcs8 -topk8 -nocrypt -in "$RUN_TMP/ls.key" -out "$d/logstash.key" \
    || { bad "could not issue the Logstash Beats certificate"; return 1; }
  cp "$ca" "$d/ca.crt"; echo "$sans" > "$d/sans"
  chmod 644 "$d/logstash.crt" "$d/ca.crt"; chmod 600 "$d/logstash.key"
  ok "Logstash Beats certificate issued for ${sans//,/ }"
}
write_logstash_config() {      # pipeline follows SOC + sensors; Logstash reloads it by itself
  mkdir -p "$ELK_DIR/logstash/pipeline" "$TOOLS_DATA"
  cat > "$ELK_DIR/logstash/logstash.yml.tmp" <<'EOF'
# GENERATED by vexor
config.reload.automatic: true
config.reload.interval: 30s
allow_superuser: true
EOF
  local wz=0 su=0 ze=0
  [ "$(soc)" = both ] && wz=1
  tool_on suricata && su=1
  tool_on zeek && ze=1
  local nf=0; [ "$(soc)" = elk ] && [ -n "$(n8n_hook)" ] && nf=1
  python3 -I - "$ELK_DIR/logstash/pipeline/vexor.conf.tmp" "$wz" "$su" "$ze" "$(env_def ZEEK_WAZUH_LOGS notice,weird,dns,http,ssl,ssh)" "$nf" "$(n8n_level)" "$(logstash_tls_on && echo 1 || echo 0)" <<'PY'
import sys
out, wz, su, ze, zl = sys.argv[1], sys.argv[2] == "1", sys.argv[3] == "1", sys.argv[4] == "1", sys.argv[5]
n8n, lvl, tls = sys.argv[6] == "1", int(sys.argv[7]), sys.argv[8] == "1"
zfiles = ", ".join(f'"/vexor-sensors/zeek/logs/{n.strip()}.log"' for n in zl.split(",") if n.strip())
beats_tls = (' ssl_enabled => true ssl_certificate => "/usr/share/logstash/certs/logstash.crt"'
             ' ssl_key => "/usr/share/logstash/certs/logstash.key" ssl_client_authentication => "none"') if tls else ""
i = ["input {", '  beats { port => 5044 tags => ["beats"]' + beats_tls + ' }']
if wz:
    i.append('  file { path => "/wazuh-logs/*/alerts/alerts.json" codec => "json" mode => "tail" start_position => "end"'
             ' sincedb_path => "/usr/share/logstash/data/sincedb-wazuh" tags => ["wazuh"] }')
if su:
    i.append('  file { path => "/vexor-sensors/suricata/log/eve.json" codec => "json" mode => "tail" start_position => "end"'
             ' sincedb_path => "/usr/share/logstash/data/sincedb-suricata" tags => ["suricata"] }')
if ze and zfiles:
    i.append(f'  file {{ path => [{zfiles}] codec => "json" mode => "tail" start_position => "end"'
             ' sincedb_path => "/usr/share/logstash/data/sincedb-zeek" tags => ["zeek"] }')
i.append("}")
f = ["filter {",
     '  if "wazuh" in [tags] or "suricata" in [tags] {',
     '    date { match => ["timestamp", "ISO8601", "yyyy-MM-dd\'T\'HH:mm:ss.SSSZ"] target => "@timestamp" tag_on_failure => ["_vexor_date_failure"] }',
     "  }",
     '  if "zeek" in [tags] {',
     '    date { match => ["ts", "UNIX"] target => "@timestamp" }',
     '    grok { match => { "[log][file][path]" => "/(?<[zeek][log]>[a-z_]+)\\.log$" } tag_on_failure => [] }',
     "  }"]
if n8n:                       # SOC=elk: no Wazuh in between - Logstash hands alerts to n8n itself
    sev = [str(k) for k, v in {1: 12, 2: 7, 3: 4}.items() if v >= lvl]
    if su and sev:
        f += ['  if "suricata" in [tags] and [event_type] == "alert" and [alert][severity] in [%s] {' % ", ".join(sev),
              '    mutate { add_tag => ["n8n"] }', "  }"]
    if ze and lvl <= 6:
        f += ['  if "zeek" in [tags] and [zeek][log] == "notice" { mutate { add_tag => ["n8n"] } }']
f.append("}")
es = '    elasticsearch { hosts => ["http://elasticsearch:9200"] user => "${VEXOR_ES_USER}" password => "${VEXOR_ES_PASSWORD}" index => "%s-%%{+YYYY.MM.dd}" }'
o = ["output {",
     '  if "wazuh" in [tags] {', es % "vexor-wazuh-alerts",
     '  } else if "suricata" in [tags] {', es % "vexor-suricata",
     '  } else if "zeek" in [tags] {', es % "vexor-zeek",
     "  } else {", es % "vexor-beats",
     "  }"]
if n8n:
    o += ['  if "n8n" in [tags] {',
          '    http { url => "${VEXOR_N8N_URL}" http_method => "post" format => "json"'
          ' headers => { "X-Vexor-Token" => "${VEXOR_N8N_TOKEN}" "X-Vexor-Source" => "logstash" } }',
          "  }"]
o.append("}")
open(out, "w").write("# GENERATED by vexor - follows SOC and SURICATA/ZEEK in .env\n" + "\n".join(i + [""] + f + [""] + o) + "\n")
PY
  local f; for f in "$ELK_DIR/logstash/logstash.yml" "$ELK_DIR/logstash/pipeline/vexor.conf"; do
    if cmp -s "$f.tmp" "$f"; then rm -f "$f.tmp"; else mv "$f.tmp" "$f"; fi
    chmod 644 "$f"
  done
}
elk_prepare() {                # before `docker compose up`
  ensure_elk_compose
  soc_elk || return 0
  gen_secret ELASTIC_PASSWORD; gen_secret KIBANA_SYSTEM_PASSWORD; gen_secret LOGSTASH_ES_PASSWORD
  gen_secret KIBANA_ENCRYPTION_KEY hex
  local p; for p in KIBANA_PORT LOGSTASH_BEATS_PORT ES_PORT; do
    [[ "$(env_def "$p" x)" =~ ^5[0-9]{4}$ ]] || die "$p=$(env_get "$p") - ELK ports must be in 50000-59999"
  done
  es_snapshot_dir >/dev/null
  logstash_certs || warn "Beats input stays without TLS until the certificate can be issued"
  write_logstash_config
}
elk_post() {                   # after `docker compose up`: users, roles, retention, data views
  soc_elk || return 0
  local i c=""
  wait_ready_run 300 0 elasticsearch >/dev/null 2>&1; c="$(es_code /_cluster/health)"
  if [ "$c" = 401 ]; then
    bad "Elasticsearch rejects ELASTIC_PASSWORD (it is set only on the FIRST start of the data volume)"
    hint "put the old value back in .env, or reset it: vexor elk reset-password"; return 1
  fi
  [ "$c" = 200 ] || { warn "Elasticsearch not ready yet (HTTP ${c:-000}) - vexor doctor --fix finishes the setup"; return 1; }
  es_curl POST /_security/user/kibana_system/_password -d "{\"password\":\"$(env_get KIBANA_SYSTEM_PASSWORD)\"}" | has -E '^\{\}$' \
    && ok "kibana_system password set" || warn "could not set the kibana_system password"
  es_curl PUT /_security/role/vexor_logstash -d '{"cluster":["monitor","manage_index_templates","manage_ilm"],
    "indices":[{"names":["vexor-*"],"privileges":["create_index","create","index","write","auto_configure","view_index_metadata"]}]}' >/dev/null
  es_curl PUT /_security/user/vexor_logstash -d "{\"password\":\"$(env_get LOGSTASH_ES_PASSWORD)\",\"roles\":[\"vexor_logstash\"],\"full_name\":\"Vexor Logstash writer\"}" \
    | has '"created"' && ok "Elasticsearch user vexor_logstash (write vexor-* only)" || warn "could not create the vexor_logstash user"
  elk_retention_apply
  wait_ready_run 300 0 kibana >/dev/null 2>&1; c="$(kibana_code)"
  if [ "$c" = 200 ]; then elk_data_views; else warn "Kibana not ready yet (HTTP ${c:-000}) - first start takes 2-3 min; vexor doctor --fix adds the data views"; fi
  return 0
}
elk_template_body() {          # index template for vexor-*: 0 replicas, mappings; $1 = ILM policy to attach (none = no lifecycle)
  local lc=""
  [ -n "${1:-}" ] && lc="\"index.lifecycle.name\":\"$1\","
  cat <<JSON
{"index_patterns":["vexor-*"],"priority":200,
 "template":{"settings":{"number_of_replicas":0,${lc}"index.mapping.total_fields.limit":5000},
   "mappings":{"dynamic_templates":[{"strings_as_keyword":{"match_mapping_type":"string","mapping":{"type":"keyword","ignore_above":1024}}}],
     "properties":{"@timestamp":{"type":"date"},"full_log":{"type":"text"},"data":{"type":"flattened"},"syscheck":{"type":"flattened"},
       "rule":{"properties":{"level":{"type":"integer"},"id":{"type":"keyword"}}}}}}}
JSON
}
elk_policy_age() {             # min_age of the live vexor-retention ILM delete phase ("none" when it is missing)
  es_curl GET /_ilm/policy/vexor-retention 2>/dev/null \
    | pj 'print(d["vexor-retention"]["policy"]["phases"]["delete"]["min_age"])' 2>/dev/null || echo none
}
elk_covered() {                # "managed of total": vexor-* indices under the vexor-retention ILM policy
  es_curl GET '/vexor-*/_ilm/explain' 2>/dev/null \
    | pj 'idx = d.get("indices", {})
print(sum(1 for v in idx.values() if v.get("policy") == sys.argv[1]), "of", len(idx))' "vexor-retention" 2>/dev/null || echo "?"
}
elk_retention_apply() {        # ILM delete after ELK_RETENTION_DAYS (else RETENTION_DAYS) + template: 0 replicas (single node); 0 days = keep forever
  local d; d="$(retention_days ELK_RETENTION_DAYS)" || { warn "ELK_RETENTION_DAYS / RETENTION_DAYS must be a whole number of days"; return 1; }
  if [ "$d" = 0 ]; then
    es_curl PUT /_index_template/vexor -d "$(elk_template_body)" | has '"acknowledged":true' || warn "could not update the vexor index template"
    es_curl PUT '/vexor-*/_settings?allow_no_indices=true' -d '{"index.lifecycle.name":null}' >/dev/null 2>&1
    es_curl DELETE /_ilm/policy/vexor-retention >/dev/null 2>&1
    ok "Elasticsearch retention: vexor-* indices kept forever (ILM policy removed)"
  else
    es_curl PUT /_ilm/policy/vexor-retention -d "{\"policy\":{\"phases\":{\"hot\":{\"actions\":{}},\"delete\":{\"min_age\":\"${d}d\",\"actions\":{\"delete\":{}}}}}}" >/dev/null
    es_curl PUT /_index_template/vexor -d "$(elk_template_body vexor-retention)" | has '"acknowledged":true' \
      && ok "Elasticsearch retention: vexor-* indices deleted after $d days (ILM), 0 replicas"
    es_curl PUT '/vexor-*/_settings?allow_no_indices=true' -d '{"index.lifecycle.name":"vexor-retention"}' >/dev/null 2>&1
  fi
  es_curl PUT '/vexor-*/_settings?allow_no_indices=true' -d '{"index":{"number_of_replicas":0}}' >/dev/null 2>&1
  return 0
}
elk_data_views() {             # Kibana data views for every vexor index family
  local id title name base; base="https://$(local_ip):$(env_def KIBANA_PORT 55601)"
  for x in "vexor-wazuh-alerts|vexor-wazuh-alerts-*|Vexor - Wazuh alerts" "vexor-suricata|vexor-suricata-*|Vexor - Suricata" \
           "vexor-zeek|vexor-zeek-*|Vexor - Zeek" "vexor-beats|vexor-beats-*|Vexor - Beats / Elastic Agent"; do
    IFS='|' read -r id title name <<<"$x"
    [ "$(curl -sk -o /dev/null -w '%{http_code}' -u "elastic:$(env_get ELASTIC_PASSWORD)" "$base/api/data_views/data_view/$id")" = 200 ] && continue
    curl -sk -o /dev/null -u "elastic:$(env_get ELASTIC_PASSWORD)" -H 'kbn-xsrf: true' -H 'Content-Type: application/json' \
      -X POST "$base/api/data_views/data_view" \
      -d "{\"data_view\":{\"id\":\"$id\",\"title\":\"$title\",\"name\":\"$name\",\"timeFieldName\":\"@timestamp\"}}"
  done
  ok "Kibana data views: Vexor - Wazuh alerts / Suricata / Zeek / Beats"
}
elk_status_lines() {           # for vexor status
  local c; c="$(es_code /_cluster/health)"
  if [ "$c" = 200 ]; then
    local h; h="$(es_curl GET /_cluster/health | pj 'print("%s  (%s shards, %s unassigned)" % (d["status"], d["active_shards"], d["unassigned_shards"]))' 2>/dev/null)"
    case "$h" in green*) ok "Elasticsearch: $h" ;; yellow*) warn "Elasticsearch: $h" ;; *) bad "Elasticsearch: $h" ;; esac
  else bad "Elasticsearch: HTTP ${c:-000}"; fi
  c="$(kibana_code)"
  if [ "$c" = 200 ]; then ok "Kibana: https://$(public_host):$(env_def KIBANA_PORT 55601)  (login elastic)"
  else warn "Kibana: HTTP ${c:-000} (first start takes 2-3 min)"; fi
  local n; n="$(es_curl GET '/vexor-*/_count?allow_no_indices=true' -d '{"query":{"range":{"@timestamp":{"gte":"now-1h"}}}}' 2>/dev/null | pj 'print(d.get("count",0))' 2>/dev/null)"
  [ -n "$n" ] && say "Events into Elasticsearch in the last hour: $n"
  return 0
}
elk_doctor() {                 # ELK checks + predictable repairs
  hdr "ELK (SOC=$(soc), Elastic $(elk_version))"
  local c st
  c="$(es_code /_cluster/health)"
  case "$c" in
    200) d_pass "Elasticsearch reachable, elastic login OK" ;;
    401) d_fail "Elasticsearch rejects ELASTIC_PASSWORD (only applied on the first start of the data volume)" "restore the old value in .env, or: vexor elk reset-password" ;;
    000|"") if ! d_starting elasticsearch; then
              d_fail "Elasticsearch not answering on 127.0.0.1:$(es_port)" "vexor logs elasticsearch   ('max virtual memory areas' = vm.max_map_count, 'OutOfMemoryError' = lower ELK_HEAP)"
              [ "$(svc_uptime_s elasticsearch)" -ge 240 ] && d_fix "restart elasticsearch" && dc restart elasticsearch >/dev/null 2>&1
            fi ;;
    *) d_fail "Elasticsearch: HTTP $c" "vexor logs elasticsearch" ;;
  esac
  if [ "$c" = 200 ]; then
    st="$(es_curl GET /_cluster/health | pj 'print(d["status"])' 2>/dev/null)"
    case "$st" in
      green) d_pass "Elasticsearch cluster green" ;;
      yellow) d_warn "Elasticsearch yellow - replica copies cannot be placed on a single node" "vexor doctor --fix (sets replicas 0)"
              d_fix "set replicas 0 on all indices" && es_curl PUT '/_all/_settings?expand_wildcards=open' -d '{"index":{"number_of_replicas":0}}' >/dev/null ;;
      *) d_fail "Elasticsearch cluster $st" "vexor elk explain" ;;
    esac
    local ro; ro="$(es_curl GET '/_all/_settings/index.blocks.read_only_allow_delete' | pj 'print(sum(1 for v in d.values() if v.get("settings",{}).get("index",{}).get("blocks",{}).get("read_only_allow_delete") == "true"))' 2>/dev/null)"
    if [ "${ro:-0}" -gt 0 ]; then
      d_fail "$ro Elasticsearch indices are read-only (disk flood stage)" "free disk or lower ELK_RETENTION_DAYS"
      d_fix "clear read-only blocks" && es_curl PUT /_all/_settings -d '{"index.blocks.read_only_allow_delete": null}' >/dev/null
    fi
    local ed; ed="$(retention_days ELK_RETENTION_DAYS)" || ed=bad
    if [ "$ed" = bad ]; then d_warn "ELK_RETENTION_DAYS / RETENTION_DAYS is not a whole number of days" "vexor config set RETENTION_DAYS 30"
    elif [ "$(elk_policy_age)" = "$(retention_expect "$ed")" ] && [ "$(es_code /_index_template/vexor)" = 200 ]; then d_pass "retention (ILM): $(retention_words "$ed") + index template present"
    else d_warn "ILM policy is $(elk_policy_age), expected $(retention_expect "$ed"), or the index template is missing" "vexor doctor --fix"; d_fix "apply ELK retention + template" && elk_retention_apply >/dev/null; fi
    if [ "$(es_code "/_snapshot/$ES_SNAP_REPO")" = 200 ]; then d_pass "Elasticsearch snapshot repository registered (vexor backup includes ELK)"
    else d_warn "Elasticsearch snapshot repository not registered yet" "vexor doctor --fix   (or the next vexor backup)"
         d_fix "register the Elasticsearch snapshot repository" && es_snapshot_register >/dev/null; fi
    if [ "$(curl -s -o /dev/null -w '%{http_code}' -u "vexor_logstash:$(env_get LOGSTASH_ES_PASSWORD)" "http://127.0.0.1:$(es_port)/_security/_authenticate")" = 200 ]; then
      d_pass "Logstash user vexor_logstash can log in"
    else d_fail "Logstash user vexor_logstash cannot log in (events are not stored)" "vexor doctor --fix"; d_fix "re-create users/roles" && elk_post >/dev/null 2>&1; fi
  fi
  c="$(kibana_code)"
  case "$c" in
    200) d_pass "Kibana https://$(public_host):$(env_def KIBANA_PORT 55601) available" ;;
    503|502) if d_starting kibana; then :
             else d_fail "Kibana not available (HTTP $c)" "vexor logs kibana   ('unable to authenticate user [kibana_system]' = password mismatch)"
                  d_fix "reset kibana_system password + restart kibana" && { es_curl POST /_security/user/kibana_system/_password -d "{\"password\":\"$(env_get KIBANA_SYSTEM_PASSWORD)\"}" >/dev/null; dc restart kibana >/dev/null 2>&1; }; fi ;;
    *) d_fail "nothing answers on Kibana port $(env_def KIBANA_PORT 55601) (HTTP ${c:-000})" "vexor doctor --fix"
       d_fix "render nginx + recreate it" && { render_override; render_nginx; dc up -d --no-deps --force-recreate nginx >/dev/null 2>&1; } ;;
  esac
  [ "$c" = 200 ] && [ "$(curl -sk -o /dev/null -w '%{http_code}' -u "elastic:$(env_get ELASTIC_PASSWORD)" "https://$(local_ip):$(env_def KIBANA_PORT 55601)/api/data_views/data_view/vexor-wazuh-alerts")" != 200 ] \
    && { d_warn "Kibana data views missing" "vexor doctor --fix"; d_fix "create the Kibana data views" && elk_data_views >/dev/null; }
  if is_running logstash; then
    local ps; ps="$(dc exec -T logstash curl -s localhost:9600/_node/stats/pipelines 2>/dev/null | pj '
p = d.get("pipelines", {}).get("main")
print("none" if p is None else "%s in / %s out" % (p["events"]["in"], p["events"]["out"]))' 2>/dev/null)"
    if [ -n "$ps" ] && [ "$ps" != none ]; then d_pass "Logstash pipeline running ($ps events)"
    else d_warn "Logstash pipeline not running yet" "vexor logs logstash   (pipeline errors are logged at start)"; fi
    [ "$(soc)" = both ] && ! dc exec -T logstash test -r /wazuh-logs/master/alerts/alerts.json 2>/dev/null \
      && d_warn "Logstash cannot read the master's alerts.json" "vexor logs logstash"
  fi
  if logstash_tls_on; then
    local ld; ld="$(cert_days_left "$LS_CERT_DIR/logstash.crt" 2>/dev/null)"
    if [ -n "$ld" ] && [ "$ld" -gt 30 ] && [ "$(cat "$LS_CERT_DIR/sans" 2>/dev/null)" != "$(logstash_sans)" ]; then
      d_warn "Beats TLS certificate does not match this machine's addresses ($(public_host)) - the IP changed?" "vexor doctor --fix"
      d_fix "re-issue the Logstash certificate" && { logstash_certs && write_logstash_config && dc restart logstash >/dev/null 2>&1; }
    elif [ -n "$ld" ] && [ "$ld" -gt 30 ]; then d_pass "Beats input uses TLS (certificate valid $ld days)"
    else d_warn "Beats TLS certificate missing or expiring (${ld:-none})" "vexor doctor --fix"
         d_fix "re-issue the Logstash certificate" && { logstash_certs && write_logstash_config; }; fi
  else
    d_warn "the Beats input on port $(env_def LOGSTASH_BEATS_PORT 55044) accepts plain TCP" "LOGSTASH_BEATS_TLS=true, vexor config apply, then: vexor elk beats-config"
  fi
  return 0
}
