n8n_test_read() {              # n8n_test_read <dir> <nonce> <notify> <abuse> <block> (1 = on): the run of the test alert
  # exit: 0 finished, 3 finished with a node error, 4 the workflow dropped the alert (token mismatch),
  #       2 still running, 1 no run with this nonce yet. Prints one line per workflow node.
  python3 -I - "$@" <<'PY'
import json, os, sqlite3, sys
db, nonce, notify, abuse, block = sys.argv[1:6]
NORMALISE = "Check token + normalise"
APPROVAL = {"Needs approval?", "Ask in chat", "Send approval request", "Wait for approval",
            "Approved?", "Wazuh API token", "Block source IP"}
def reason(name):
    if name in ("Format message", "Send to chat") and notify != "1": return " (N8N_NOTIFY_URL empty)"
    if name in ("AbuseIPDB lookup", "Keep alert fields") and abuse != "1": return " (N8N_ABUSEIPDB_KEY empty)"
    if name in APPROVAL and block != "1": return " (N8N_AUTO_BLOCK=approve and N8N_NOTIFY_URL)"
    return ""
def unflatted(text):
    # n8n stores execution data in flatted format: a list whose strings are indexes into the list
    arr = json.loads(text)
    seen = {}
    def at(i):
        if i in seen: return seen[i]
        v = arr[i]
        if isinstance(v, dict):
            out = seen[i] = {}
            for k, x in v.items(): out[k] = ref(x)
        elif isinstance(v, list):
            out = seen[i] = []
            out.extend(ref(x) for x in v)
        else:
            out = seen[i] = v
        return out
    def ref(x):
        return at(int(x)) if isinstance(x, str) else x
    return at(0)
con = sqlite3.connect(os.path.join(db, "database.sqlite"))
rows = con.execute("SELECT e.id, e.status, d.workflowData, d.data FROM execution_entity e "
                   "JOIN execution_data d ON d.executionId = e.id WHERE d.data LIKE '%' || ? || '%' "
                   "ORDER BY e.id DESC LIMIT 5", (nonce,)).fetchall()
con.close()
if not rows:
    sys.exit(1)
ex_id, status, wf_text, data_text = rows[0]
wf = json.loads(wf_text)
result = (unflatted(data_text) or {}).get("resultData") or {}
run = result.get("runData") or {}
out = [f'Execution {ex_id} of "{wf.get("name", "?")}": {status}']
code = 0
for name in [n.get("name", "") for n in wf.get("nodes", []) if n.get("type") != "n8n-nodes-base.stickyNote"]:
    runs = run.get(name)
    if not runs:
        out.append(f"  – {name}{reason(name)}")
        continue
    last = runs[-1]
    items = sum(len(o or []) for o in ((last.get("data") or {}).get("main") or []))
    if last.get("error"):
        out.append(f"  ✘ {name}: {last['error'].get('message', 'error')}")
        code = max(code, 3)
    elif name == NORMALISE and items == 0:
        out.append(f"  ✘ {name}: dropped the alert - token mismatch")
        code = 4
    elif last.get("executionStatus") == "waiting":
        out.append(f"  … {name} (waiting for approval, up to 1 hour)")
    else:
        out.append(f"  ✔ {name}")
if result.get("error"):
    out.append(f"  ✘ workflow error: {result['error'].get('message', 'error')}")
    code = max(code, 3)
if status in ("new", "running") and code == 0:
    code = 2
print("\n".join(out))
sys.exit(code)
PY
}
n8n_test() {                   # vexor n8n test [--level N] [--srcip IP]: a fake alert through the published workflow
  local level=12 srcip=192.0.2.10 url tok nonce body res code dir deadline out rc notify abuse block
  while [ $# -gt 0 ]; do
    case "$1" in
      --level) level="${2:?--level needs a number}"; shift ;;
      --srcip) srcip="${2:?--srcip needs an IPv4 address}"; shift ;;
      *) die "usage: vexor n8n test [--level N] [--srcip IP]" ;;
    esac
    shift
  done
  [[ "$level" =~ ^([0-9]|1[0-5])$ ]] || die "--level must be 0-15"
  [[ "$srcip" =~ ^([0-9]{1,3}\.){3}[0-9]{1,3}$ ]] || die "--srcip must be an IPv4 address"
  url="$(n8n_hook)"; [ -n "$url" ] || die "not connected - vexor n8n connect"
  [[ "$url" == http://n8n:5678/* ]] || die "alerts go to $url, not to this stack's n8n - n8n test reads only this n8n's executions"
  tok="$(env_get N8N_HOOK_TOKEN)"; [ -n "$tok" ] || die "no N8N_HOOK_TOKEN in .env - vexor n8n connect"
  is_running n8n || die "n8n is not running - vexor n8n enable"

  nonce="vexor-test-$(date +%s)-$$"
  body="$(printf '{"timestamp":"%s","rule":{"level":%s,"id":"100000","description":"Vexor test alert","groups":["vexor","test"]},"agent":{"id":"000","name":"vexor-test"},"manager":{"name":"vexor-test"},"id":"%s","full_log":"vexor n8n test %s","location":"vexor","data":{"srcip":"%s"}}' \
    "$(date -u +%Y-%m-%dT%H:%M:%S.000+0000)" "$level" "$nonce" "$nonce" "$srcip")"
  # posted from inside the n8n container: the request reaches the webhook over the stack network, like a manager's.
  # Right after a restart (vexor n8n workflow restarts n8n) n8n answers /healthz before it has registered the
  # published webhooks, so 404 / no answer is retried for up to 45 s. Neither starts an execution, so no double alert.
  local post_end=$((SECONDS + 45)) waited=0
  while :; do
    res="$(dc exec -T -e "VEXOR_URL=$url" -e "VEXOR_TOKEN=$tok" -e "VEXOR_BODY=$body" n8n node -e '
fetch(process.env.VEXOR_URL, {method: "POST", headers: {"Content-Type": "application/json", "X-Vexor-Token": process.env.VEXOR_TOKEN}, body: process.env.VEXOR_BODY})
  .then(async (r) => console.log(r.status + " " + (await r.text()).slice(0, 200).replace(/\s+/g, " ")), (e) => console.log("0 " + String(e.cause || e)));' 2>/dev/null)"
    code="${res%% *}"
    [[ "$code" =~ ^(404|0|)$ ]] && [ "$SECONDS" -lt "$post_end" ] || break
    [ "$waited" = 1 ] || say "n8n has not registered the webhook yet (just restarted?) - retrying for up to 45 s"
    waited=1; sleep 3
  done
  case "$code" in
    2??) ;;
    404) die "the workflow is not published at $url (HTTP 404) - vexor n8n workflow   (imports and publishes it)" ;;
    0) die "n8n did not answer at $url from inside its container: ${res#0 }" ;;
    *) die "n8n answered HTTP ${code:-none} for the test alert: ${res#* }" ;;
  esac
  say "test alert sent: level $level, src $srcip, rule 100000 \"Vexor test alert\" (HTTP $code)"

  dir="$(mktemp -d "$RUN_TMP/n8n-test.XXXXXX")"
  notify="$([ -n "$(env_get N8N_NOTIFY_URL)" ] && echo 1 || echo 0)"
  abuse="$([ -n "$(env_get N8N_ABUSEIPDB_KEY)" ] && echo 1 || echo 0)"
  block="$([ "$(env_def N8N_AUTO_BLOCK off)" = approve ] && [ "$notify" = 1 ] && echo 1 || echo 0)"
  deadline=$((SECONDS + 40)); rc=1; out=""
  while :; do
    if n8n_db_copy "$dir"; then
      out="$(n8n_test_read "$dir" "$nonce" "$notify" "$abuse" "$block")"; rc=$?
    fi
    { [ "$rc" = 0 ] || [ "$rc" = 3 ] || [ "$rc" = 4 ]; } && break
    [ "$SECONDS" -ge "$deadline" ] && break
    sleep 2
  done
  rm -rf "$dir"
  [ -n "$out" ] && printf '%s\n' "$out" | sed 's/^/  /'
  case "$rc" in
    0) ok "n8n ran the workflow for the test alert" ;;
    2) warn "still running after 40 s - see the run in n8n: Executions"; return 1 ;;
    3) bad "the workflow ran, with an error (above)"; return 1 ;;
    4) bad "token mismatch: the workflow in n8n checks another N8N_HOOK_TOKEN - vexor n8n workflow   (re-imports it with the current token)"; return 1 ;;
    *) bad "n8n accepted the alert, but no run of it appeared within 40 s"; hint "vexor logs n8n"; return 1 ;;
  esac
}
n8n_backup() {                 # workflows + credentials (encrypted with N8N_ENCRYPTION_KEY - keep .env with it)
  is_running n8n || die "n8n is not running"
  local out; out="${1:-$(backup_dir)/n8n-$(date +%Y%m%d-%H%M%S)}"; mkdir -p "$out"
  dc exec -T n8n sh -c 'rm -rf /tmp/vexor-n8n && mkdir -p /tmp/vexor-n8n && n8n export:workflow --all --separate --output=/tmp/vexor-n8n/workflows >/dev/null 2>&1; n8n export:credentials --all --separate --output=/tmp/vexor-n8n/credentials >/dev/null 2>&1; true'
