# Sourced by ./vexor in a fixed order (see the loader there); not executable on its own.
# ============================================================== n8n automation (SOAR)
# Alerts -> n8n : SOC wazuh|both - Wazuh integration "custom-n8n" on EVERY manager (agents are balanced
#                 over master + workers) posts each alert with level >= N8N_ALERT_LEVEL as JSON to an n8n
#                 webhook, with the header X-Vexor-Token: N8N_HOOK_TOKEN.
#                 SOC elk - Logstash posts Suricata alerts and Zeek notices to the same webhook.
# n8n -> stacks : vexor n8n credentials - least-privilege users for n8n workflows (Wazuh API: agents +
#                 active response; Elasticsearch: read vexor-*), reached on the internal Docker network.
N8N_SCRIPT_NAME="custom-n8n"
n8n_hook() { env_get N8N_HOOK_URL; }
n8n_level() { env_def N8N_ALERT_LEVEL 7; }
n8n_conf_files() { echo "$CLUSTER_DIR/wazuh_manager.conf"; ls "$CLUSTER_DIR"/wazuh_worker*.conf 2>/dev/null; }
n8n_hook_url() {               # <path | url> -> URL the managers / Logstash use (n8n of this stack = internal address)
  python3 -I - "$1" "$(public_host)" "$(tool_port n8n)" <<'PY'
import sys
from urllib.parse import urlsplit
v, host, port = sys.argv[1].strip(), sys.argv[2], sys.argv[3]
TEST_NOTE = "n8n test URL (webhook-test) replaced by the production URL: the test URL answers only one call after 'Execute workflow'"
if "://" not in v:
    v = v.strip("/")
    if v.startswith("webhook-test/"):
        v = "webhook/" + v[len("webhook-test/"):]
        print(TEST_NOTE, file=sys.stderr)
    if not v.startswith("webhook/"):
        v = "webhook/" + v
    print("http://n8n:5678/" + v)
    sys.exit()
u = urlsplit(v)
ours = u.hostname == "n8n" or (u.hostname in (host, "localhost", "127.0.0.1") and str(u.port) == port)
path = u.path
if ours and path.startswith("/webhook-test/"):
    path = "/webhook/" + path[len("/webhook-test/"):]
    print(TEST_NOTE, file=sys.stderr)
print("http://n8n:5678" + path + ("?" + u.query if u.query else "") if ours else v)
PY
}
n8n_write_script() {           # the integration script installed into every manager
  mkdir -p "$TOOLS_DIR/wazuh"
  cat > "$TOOLS_DIR/wazuh/$N8N_SCRIPT_NAME.py" <<'EOF'
# GENERATED by vexor - Wazuh -> n8n (custom integration "custom-n8n"). Do not edit: vexor n8n connect rewrites it.
# wazuh-integratord calls: custom-n8n <alert_file> <api_key> <hook_url> [debug]
# The whole alert is posted as JSON; <api_key> is sent as X-Vexor-Token so the workflow can reject other callers.
import json
import sys
import time

import requests

LOG = "/var/ossec/logs/integrations.log"


def log(msg):
    try:
        with open(LOG, "a") as f:
            f.write(time.strftime("%Y/%m/%d %H:%M:%S") + " custom-n8n: " + msg + "\n")
    except OSError:
        pass


def main(argv):
    if len(argv) < 4:
        log("bad arguments: %s" % argv[1:])
        sys.exit(2)
    alert_file, token, url = argv[1], argv[2], argv[3]
    try:
        with open(alert_file) as f:
            alert = json.load(f)
    except (OSError, ValueError) as e:
        log("cannot read the alert: %s" % e)
        sys.exit(6)
    headers = {"X-Vexor-Token": token, "X-Vexor-Source": "wazuh"}
    requests.packages.urllib3.disable_warnings()
    for attempt in (1, 2, 3):
        try:
            r = requests.post(url, json=alert, headers=headers, timeout=10, verify=False)
            if r.status_code < 300:
                return
            log("HTTP %s from %s: %s" % (r.status_code, url, r.text[:200].replace("\n", " ")))
            if r.status_code == 404:          # workflow not published / wrong path: retrying cannot help
                break
        except requests.RequestException as e:
            log("attempt %d to %s: %s" % (attempt, url, e))
        time.sleep(attempt)
    sys.exit(1)


if __name__ == "__main__":
    main(sys.argv)
EOF
  chmod 644 "$TOOLS_DIR/wazuh/$N8N_SCRIPT_NAME.py"
}
n8n_script_current() {         # n8n_script_current <manager>: installed and identical to the generated one
  local want got; want="$(md5sum < "$TOOLS_DIR/wazuh/$N8N_SCRIPT_NAME.py" 2>/dev/null | cut -d' ' -f1)"
  got="$(dc exec -T "$1" sh -c "test -x /var/ossec/integrations/$N8N_SCRIPT_NAME && md5sum < /var/ossec/integrations/$N8N_SCRIPT_NAME.py" 2>/dev/null | cut -d' ' -f1)"
  [ -n "$want" ] && [ "$want" = "$got" ]
}
n8n_install_script() {         # Wazuh python launcher (same as slack) + our script into each running manager's integrations volume
  n8n_write_script
  local m rc=0
  for m in $(enabled_managers); do
    is_running "$m" || continue
    n8n_script_current "$m" && continue
    if dc exec -T "$m" sh -c "d=/var/ossec/integrations; cp \$d/slack \$d/$N8N_SCRIPT_NAME && cat > \$d/$N8N_SCRIPT_NAME.py \
         && chown root:wazuh \$d/$N8N_SCRIPT_NAME \$d/$N8N_SCRIPT_NAME.py && chmod 750 \$d/$N8N_SCRIPT_NAME \$d/$N8N_SCRIPT_NAME.py" \
         < "$TOOLS_DIR/wazuh/$N8N_SCRIPT_NAME.py"; then
      say "$m: integration script $N8N_SCRIPT_NAME installed"; N8N_INSTALLED="${N8N_INSTALLED:-} $m"
    else bad "$m: could not install $N8N_SCRIPT_NAME"; rc=1; fi
  done
  return "$rc"
}
n8n_sync_blocks() {            # <integration> block in master + worker configs (also drops old Shuffle blocks);
  local url="" lvl grp tok         # prints "changed" when a file was edited
  soc_wazuh && url="$(n8n_hook)"
  lvl="$(n8n_level)"; grp="$(env_get N8N_ALERT_GROUPS)"; tok="$(env_get N8N_HOOK_TOKEN)"
  python3 -I - "$url" "$lvl" "$grp" "$tok" "$(env_get N8N_EXTRA_HOOKS)" $(n8n_conf_files) <<'PY'
import re, sys
from xml.sax.saxutils import escape
url, level, groups, token, extra, files = sys.argv[1], sys.argv[2], sys.argv[3], sys.argv[4], sys.argv[5], sys.argv[6:]


def integ(u, lv, gr):
    return ("  <integration>\n"
            "    <name>custom-n8n</name>\n"
            f"    <hook_url>{escape(u)}</hook_url>\n"
            f"    <api_key>{escape(token)}</api_key>\n"
            + (f"    <level>{lv}</level>\n" if lv not in ("", "0") else "")      # 0 = every alert: Wazuh needs no <level> for that
            + (f"    <group>{escape(gr)}</group>\n" if gr else "")
            + "    <alert_format>json</alert_format>\n"
            "  </integration>\n")


extras = [e.split("|") for e in extra.split(";") if e.count("|") == 2]


def prod(u):                           # this stack's n8n: the test URL works for one call after "Execute workflow" only
    return "http://n8n:5678/webhook/" + u[len("http://n8n:5678/webhook-test/"):] if u.startswith("http://n8n:5678/webhook-test/") else u


url = prod(url)
extras = [(prod(u), lv, gr) for u, lv, gr in extras]
block = ("  <!-- vexor:n8n:begin (managed by: vexor n8n) -->\n" + integ(url, level, groups)
         + "".join(integ(u, lv, gr) for u, lv, gr in extras)
         + "  <!-- vexor:n8n:end -->\n")
changed = False
for f in files:
    s = open(f).read(); o = s
    s = re.sub(r"[ \t]*<!-- (?:vexor|wazuhctl):shuffle:begin.*?<!-- (?:vexor|wazuhctl):shuffle:end -->\n?", "", s, flags=re.S)
    pat = re.compile(r"[ \t]*<!-- (?:vexor|wazuhctl):n8n:begin.*?<!-- (?:vexor|wazuhctl):n8n:end -->\n?", re.S)
    want = block if url else ""
    if pat.search(s):                  # replace in place: keeps its position next to the sensors block
        first = [True]
        s = pat.sub(lambda m: (want if first.pop() else "") if first else "", s)
    elif want:
        s = s.replace("</ossec_config>", want + "</ossec_config>", 1)
    if s != o:
        open(f, "w").write(s)          # in-place write keeps the bind-mounted inode
        changed = True
print("changed" if changed else "")
PY
}
n8n_probe() {                  # webhook state seen from the managers' network: registered | inactive | down
  local body svc=wazuh.master
  soc_wazuh || svc=logstash
  is_running "$svc" || { echo down; return 0; }
  body="$(dc exec -T "$svc" curl -sk --max-time 8 "$(n8n_hook)" 2>/dev/null)"
  case "$body" in
    *"not registered for GET"*|*"not registered for the GET"*) echo registered ;;
    *"is not registered"*|*"not registered"*) echo inactive ;;
    "") echo down ;;
    *) echo registered ;;
  esac
}
