n8n_status() {
  hdr "n8n (automation / SOAR)"
  if tool_on n8n; then
    is_running n8n && ok "running: https://$(public_host):$(tool_port n8n)" || bad "N8N=true but the container is not running - vexor logs n8n"
    if is_running n8n; then
      n8n_owner_set && ok "owner account created" || warn "no owner account yet - open n8n now: the FIRST visitor becomes the owner"
      local wf; wf="$(dc exec -T n8n n8n list:workflow 2>/dev/null | grep -v '^$' | wc -l)"
      say "workflows: ${wf:-0}  (vexor n8n workflow imports the 'Vexor - SOC alerts' starter)"
    fi
  else
    say "N8N=false (a separate n8n can still receive alerts: vexor n8n connect <full webhook URL>)"
  fi
  hdr "Alerts -> n8n"
  local url; url="$(n8n_hook)"
  if [ -z "$url" ]; then warn "not connected - vexor n8n connect [webhook-path]   (default path: vexor-alerts)"; return 0; fi
  say "webhook : $url   level >= $(n8n_level)   groups: $(env_def N8N_ALERT_GROUPS '(all)')"
