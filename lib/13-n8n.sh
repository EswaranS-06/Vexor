  chmod -R go-rwx "$out"
  ok "n8n backup: $out ($(find "$out" -name '*.json' | wc -l) files; credentials stay encrypted with N8N_ENCRYPTION_KEY)"
}
cmd_n8n() {
  local sub="${1:-status}"; shift || true
  case "$sub" in
    status) n8n_status ;;
    enable|disable|on|off) cmd_tools "$sub" n8n ;;
    connect)
      local target="vexor-alerts" lvl grp
      [ $# -gt 0 ] && [[ "$1" != --* ]] && { target="$1"; shift; }
      lvl="$(n8n_level)"; grp="$(env_get N8N_ALERT_GROUPS)"
      local extra; extra="$(env_get N8N_EXTRA_HOOKS)"
      while [ $# -gt 0 ]; do case "$1" in --level) lvl="${2:?}"; shift ;; --groups) grp="${2:-}"; shift ;; --extra) extra="${2:-}"; shift ;; esac; shift; done
      [[ "$lvl" =~ ^([0-9]|1[0-5])$ ]] || die "--level must be 0-15"
      [[ "$target" == *://* ]] || tool_on n8n || die "N8N is not enabled: vexor n8n enable   (or give the full webhook URL of another n8n)"
      local url; url="$(n8n_hook_url "$target")"
      take_lock
      gen_secret N8N_HOOK_TOKEN hex
      env_set N8N_HOOK_URL "$url"; env_set N8N_ALERT_LEVEL "$lvl"; env_set N8N_ALERT_GROUPS "$grp"; env_set N8N_EXTRA_HOOKS "$extra"
      ok "alerts -> $url  (level >= $lvl${grp:+, groups $grp}; header X-Vexor-Token)"
      local e; for e in ${extra//;/ }; do IFS='|' read -r eu el eg <<<"$e"; ok "alerts -> $eu  (level >= ${el:-0}${eg:+, groups $eg})"; done
      n8n_apply
      [ "$(n8n_probe)" = registered ] || hint "no workflow listens on that path yet: vexor n8n workflow   (imports + publishes a starter)" ;;
    disconnect)
      take_lock
      env_set N8N_HOOK_URL ""; env_set N8N_EXTRA_HOOKS ""; n8n_apply; ok "the stack no longer sends alerts to n8n" ;;
    test) n8n_test "$@" ;;
    workflow)
      case "${1:-import}" in
        import) take_lock; [ -n "$(n8n_hook)" ] || die "connect first: vexor n8n connect"; n8n_workflow_import ;;
        file|export) mkdir -p "$TOOLS_DIR/n8n"; n8n_workflow_json > "$TOOLS_DIR/n8n/vexor-soc-alerts.workflow.json"
                     ok "$TOOLS_DIR/n8n/vexor-soc-alerts.workflow.json  (n8n: Workflows -> Import from file)" ;;
        *) die "usage: vexor n8n workflow [import] | file" ;;
      esac ;;
    credentials|creds|api-user) n8n_credentials ;;
    backup) n8n_backup "$@" ;;
    reset-owner)
      is_running n8n || die "n8n is not running"
      confirm "Remove ALL n8n user accounts? Workflows and credentials are kept; the next visitor creates the owner again." || die "Aborted"
      dc exec -T n8n n8n user-management:reset >/dev/null 2>&1 && dc restart n8n >/dev/null 2>&1 \
        && ok "n8n users reset - open https://$(public_host):$(tool_port n8n) and create the owner now" ;;
    logs) cmd_logs n8n "$@" ;;
    *) die "usage: vexor n8n [status] | enable | disable | connect [path|url] [--level N] [--groups G] | disconnect | test [--level N] [--srcip IP]
                | workflow [import|file] | credentials | backup [dir] | reset-owner | logs [-f]" ;;
  esac
}

