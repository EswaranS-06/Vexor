n8n_apply() {                  # after connect/disconnect/level change: configs, script, reload what reads them
  if soc_wazuh; then
    local ch restart; ch="$(n8n_sync_blocks)"
    N8N_INSTALLED=""
    [ -n "$(n8n_hook)" ] && n8n_install_script
    if [ "$ch" = changed ]; then restart="$(enabled_managers)"; else restart="$N8N_INSTALLED"; fi
    if [ -n "${restart// /}" ]; then
      say "recreating $(echo $restart | tr '
' ' ')to load the integration (agents reconnect by themselves) ..."
      dc_restart $restart >/dev/null 2>&1
      local m; for m in $restart; do
        [ -n "$(n8n_hook)" ] || continue
        if wait_daemon "$m" wazuh-integratord 150; then ok "$m: integratord running - alerts level >= $(n8n_level) go to n8n"
        else bad "$m: integratord not running after 150s - vexor logs ossec $m"; fi
      done
    fi
  fi
  if soc_elk; then
    write_logstash_config
    is_running logstash && { dc up -d --no-deps logstash >/dev/null 2>&1; ok "Logstash pipeline updated"; }
  fi
  return 0
}
n8n_doctor() {                 # alerts -> n8n path: config blocks, script per manager, webhook registered
  hdr "n8n alert forwarding"
  if soc_wazuh; then
    local f m
    for f in $(n8n_conf_files); do
      grep -q 'vexor:n8n:begin' "$f" || { d_fail "$(basename "$f") has no n8n integration" "vexor n8n connect"; d_fix "write the integration blocks" && n8n_apply; break; }
    done
    for m in $(enabled_managers); do
      is_running "$m" || continue
      if n8n_script_current "$m"; then d_pass "$m: custom-n8n script installed"
      else d_fail "$m: custom-n8n script missing/outdated (alerts are not delivered)" "vexor doctor --fix"
           d_fix "install the script + recreate $m" && { N8N_INSTALLED=""; n8n_install_script && dc_restart "$m" >/dev/null 2>&1; }; fi
    done
  fi
  case "$(n8n_probe)" in
    registered) d_pass "n8n webhook registered ($(n8n_hook))" ;;
    inactive) d_warn "n8n webhook not registered - the workflow is not published" "vexor n8n workflow   (or publish your workflow in n8n)" ;;
    *) d_fail "n8n not reachable from the stack ($(n8n_hook))" "vexor n8n status   (N8N enabled? URL right?)" ;;
  esac
}
