      grep -q 'vexor:n8n:begin' "$f" && ok "$(basename "$f") has the integration" || bad "$(basename "$f") is missing it - vexor n8n connect"
    done
    for m in $(enabled_managers); do
      is_running "$m" || continue
      n8n_script_current "$m" && ok "$m: script installed" || bad "$m: integration script missing/outdated - vexor doctor --fix"
      daemon_list "$m" | has '^wazuh-integratord is running' && ok "$m: integratord running" || bad "$m: integratord NOT running - vexor logs ossec $m"
    done
  fi
  if [ "$(soc)" = elk ]; then
