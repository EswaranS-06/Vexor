  case "$(n8n_probe)" in
    registered) ok "webhook is registered (workflow published)" ;;
    inactive) warn "webhook not registered: publish the workflow in n8n (or: vexor n8n workflow)" ;;
    *) bad "n8n not reachable from the stack at $url" ;;
  esac
  if soc_wazuh && is_running wazuh.master; then
    local e; e="$(dc exec -T wazuh.master sh -c 'c="$(date -u -d "-15 min" "+%Y/%m/%d %H:%M:%S")"; grep custom-n8n /var/ossec/logs/integrations.log 2>/dev/null | awk -v c="$c" "substr(\$0,1,19) >= c" | tail -n 3' 2>/dev/null)"
    if [ -n "$e" ]; then say "delivery errors in the last 15 min (master):"; cut -c1-220 <<<"$e" | sed 's/^/    /'
    else ok "no delivery errors in the last 15 min"; fi
  fi
  hdr "n8n -> stacks (credentials)"
  soc_wazuh && { [ -n "$(env_get WAZUH_N8N_PASSWORD)" ] && ok "Wazuh API user $(env_def WAZUH_N8N_USER vexor-n8n)" || say "Wazuh API user: not created - vexor n8n credentials"; }
  soc_elk && { [ -n "$(env_get ES_N8N_PASSWORD)" ] && [ "$(env_get ES_N8N_PASSWORD)" != CHANGE_ME ] && ok "Elasticsearch user vexor_n8n" || say "Elasticsearch user: not created - vexor n8n credentials"; }
  return 0
}
